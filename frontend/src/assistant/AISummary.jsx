import { useEffect, useId, useRef, useState } from 'react'
import { Link, useLocation } from 'react-router-dom'
import { ChevronDown, ChevronUp, ExternalLink, X } from 'lucide-react'
import { prefersReducedMotion, useAssistantOptional } from './AssistantProvider'
import { cn } from '../lib/utils'

// 13 Oct: the AI overview at the top of the page the navigator just opened. A quiet block, no card: a 3 px vertical
// spectrum rule on the left; a header row in the "AI Overview" manner — a four-point star filled with the logo's
// spectrum, the words "AI Overview", and at the right end the small "Generated by HCDP AI" and the ✕; then the
// numbered sources FIRST ("From HCDP: ¹ Hurricane Lowell report ↗ · ² Access Data ↗", external, new tab); then the
// summary's sentences, each fading and rising CHUNK_STAGGER_MS apart (reduced motion: all at once), each ending in
// small superscript links to the sources it rests on; then "Show more ⌄", which unfolds (same fade) the "more"
// sentences, "Also:" (the navigator's alternatives for this answer) and the follow-up asks as tappable rows (a tap
// sends that question), and reads "Show less ⌃" open. Collapsed on every new overview; nothing persisted.
// It renders only while the provider holds an overview for this very pathname — never on a direct load — and is
// keyed by the answer's id, so a new answer for the same page fades in again. While the overview is still being
// written the block shows its header and a small comet ring.
export const CHUNK_STAGGER_MS = 350
const SUP = '⁰¹²³⁴⁵⁶⁷⁸⁹'
export const superscript = (n) => String(n).split('').map((d) => SUP[Number(d)] ?? d).join('')

export default function AISummary({ className, scrollIntoView = false }) {
  const assistant = useAssistantOptional()
  const { pathname } = useLocation()
  const summary = assistant?.summary
  if (!summary || summary.path !== pathname) return null
  return <SummaryBlock key={summary.id} summary={summary} onDismiss={assistant.dismissSummary} send={assistant.send} className={className} scrollIntoView={scrollIntoView} />
}

/** The logo's spectrum as a four-point star (the AI Overview mark). */
function Star({ id }) {
  return (
    <svg width="14" height="14" viewBox="0 0 24 24" aria-hidden="true" className="shrink-0" data-testid="ai-overview-star">
      <defs>
        <linearGradient id={id} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#c9503c" /><stop offset="0.2" stopColor="#cb6f24" /><stop offset="0.4" stopColor="#e8b84b" />
          <stop offset="0.6" stopColor="#86b45f" /><stop offset="0.8" stopColor="#3f8f8b" /><stop offset="1" stopColor="#303078" />
        </linearGradient>
      </defs>
      <path d="M12 1.5 C13.2 7.6 16.4 10.8 22.5 12 C16.4 13.2 13.2 16.4 12 22.5 C10.8 16.4 7.6 13.2 1.5 12 C7.6 10.8 10.8 7.6 12 1.5 Z" fill={`url(#${id})`} />
    </svg>
  )
}

/** The superscript source links after a sentence. */
function Cites({ cites, sources, testid }) {
  const list = (cites || []).filter((k) => sources[k - 1])
  if (!list.length) return null
  return (
    <span className="ml-0.5 whitespace-nowrap" data-testid={testid}>
      {list.map((k) => (
        <a key={k} href={sources[k - 1].url} target="_blank" rel="noopener noreferrer" className="ml-px text-[10px] text-subtle hover:underline" title={sources[k - 1].title} data-testid="ai-summary-cite">
          {superscript(k)}<span className="sr-only"> source {k}: {sources[k - 1].title} (opens in a new tab)</span>
        </a>
      ))}
    </span>
  )
}

function Chunks({ chunks, cites, sources, reduce, testid, chunkTestid }) {
  return (
    <div className="max-w-3xl text-[15px] leading-relaxed" data-testid={testid}>
      {chunks.map((c, i) => (
        <p key={i} className="hcdp-ai-chunk" style={reduce ? undefined : { animationDelay: `${i * CHUNK_STAGGER_MS}ms` }} data-testid={chunkTestid}>
          {c}<Cites cites={cites?.[i]} sources={sources} testid={`${chunkTestid}-cites`} />
        </p>
      ))}
    </div>
  )
}

function SummaryBlock({ summary, onDismiss, send, className, scrollIntoView }) {
  const ref = useRef(null)
  const gradId = useId().replace(/:/g, '')
  const [open, setOpen] = useState(false)   // collapsed on every new overview
  // The data page shows the block above its Export form, further down the page: bring it into view on arrival
  // (after the shell's scroll-to-top, which runs in a parent effect).
  useEffect(() => {
    if (!scrollIntoView) return undefined
    const t = window.setTimeout(() => ref.current?.scrollIntoView?.({ block: 'start', behavior: prefersReducedMotion() ? 'auto' : 'smooth' }), 80)
    return () => window.clearTimeout(t)
  }, [scrollIntoView])
  const reduce = prefersReducedMotion()
  const { status, chunks = [], cites = [], more = [], moreCites = [], sources = [], followups = [], alternatives = [] } = summary
  const hasMore = more.length > 0 || alternatives.length > 0 || followups.length > 0
  return (
    <section ref={ref} aria-label="AI Overview" data-testid="ai-summary" data-status={status} className={cn('hcdp-ai-summary relative pl-4', className)} style={{ scrollMarginTop: 'calc(var(--hcdp-sticky-h, 7rem) + 1rem)' }}>
      <span aria-hidden="true" className="hcdp-ai-summary-rule" />
      <div className="flex items-center gap-2" data-testid="ai-summary-header">
        <Star id={gradId} />
        <span className="text-[13px] font-medium text-foreground" data-testid="ai-overview-title">AI Overview</span>
        <span className="ml-auto text-[11px] text-subtle" data-testid="ai-summary-eyebrow">Generated by <span className="hcdp-ai-words">HCDP AI</span></span>
        <button type="button" onClick={onDismiss} aria-label="Dismiss the AI overview" data-testid="ai-summary-dismiss"
          className="-mr-1 grid h-7 w-7 shrink-0 place-items-center rounded-md text-subtle hover:bg-muted hover:text-foreground [@media(pointer:coarse)]:h-11 [@media(pointer:coarse)]:w-11">
          <X className="h-3.5 w-3.5" aria-hidden="true" />
        </button>
      </div>
      {status === 'pending' && (
        <p className="mt-1.5 flex items-center gap-2 text-sm text-subtle" role="status" data-testid="ai-summary-pending">
          <span className="hcdp-comet-ring hcdp-comet-ring-sm" aria-hidden="true" />Writing an overview of this page…
        </p>
      )}
      {status === 'ready' && (
        <>
          {sources.length > 0 && (
            <p className="mt-1.5 text-[13px] text-subtle" data-testid="ai-summary-sources">
              From HCDP:{' '}
              {sources.map((s, i) => (
                <span key={s.url}>
                  {i > 0 && ' · '}
                  <a href={s.url} target="_blank" rel="noopener noreferrer" className="underline underline-offset-2 hover:text-foreground">
                    <span className="sr-only">source {i + 1}: </span><span aria-hidden="true">{superscript(i + 1)} </span>{s.title}<span aria-hidden="true"> ↗</span><span className="sr-only"> (opens in a new tab)</span>
                  </a>
                </span>
              ))}
            </p>
          )}
          <div className="mt-1.5">
            <Chunks chunks={chunks} cites={cites} sources={sources} reduce={reduce} testid="ai-summary-text" chunkTestid="ai-summary-chunk" />
          </div>
          {hasMore && (
            <>
              {open && (
                <div className="mt-3 space-y-3" data-testid="ai-summary-more">
                  {more.length > 0 && <Chunks chunks={more} cites={moreCites} sources={sources} reduce={reduce} testid="ai-summary-more-text" chunkTestid="ai-summary-more-chunk" />}
                  {alternatives.length > 0 && (
                    <p className="hcdp-ai-chunk text-[13px] text-subtle" style={reduce ? undefined : { animationDelay: `${more.length * CHUNK_STAGGER_MS}ms` }} data-testid="ai-summary-also">
                      Also:{' '}
                      {alternatives.map((a, j) => (
                        <span key={`${a.url}-${j}`}>
                          {j > 0 && ' · '}
                          {a.url.startsWith('/')
                            ? <Link to={a.url} className="underline underline-offset-2 hover:text-foreground">{a.title}</Link>
                            : <a href={a.url} target="_blank" rel="noopener noreferrer" className="underline underline-offset-2 hover:text-foreground">{a.title}<ExternalLink className="ml-0.5 inline h-3 w-3" aria-label="opens in a new tab" /></a>}
                        </span>
                      ))}
                    </p>
                  )}
                  {followups.length > 0 && (
                    <ul className="hcdp-ai-chunk divide-y divide-border rounded-lg border border-border" style={reduce ? undefined : { animationDelay: `${(more.length + (alternatives.length ? 1 : 0)) * CHUNK_STAGGER_MS}ms` }} aria-label="Follow-up questions" data-testid="ai-summary-followups">
                      {followups.map((f) => (
                        <li key={f}>
                          <button type="button" onClick={() => send?.(f)} className="flex min-h-9 w-full items-center justify-between gap-3 px-3 py-1.5 text-left text-[13px] hover:bg-muted [@media(pointer:coarse)]:min-h-11" data-testid="ai-summary-followup">
                            <span>{f}</span><span aria-hidden="true" className="text-subtle">↵</span>
                          </button>
                        </li>
                      ))}
                    </ul>
                  )}
                </div>
              )}
              <button type="button" onClick={() => setOpen((o) => !o)} aria-expanded={open}
                className="mt-3 flex h-9 w-full items-center justify-center gap-1 rounded-full border border-border text-[13px] text-foreground hover:bg-muted [@media(pointer:coarse)]:min-h-11" data-testid="ai-summary-toggle">
                {open ? <>Show less <ChevronUp className="h-4 w-4" aria-hidden="true" /></> : <>Show more <ChevronDown className="h-4 w-4" aria-hidden="true" /></>}
              </button>
            </>
          )}
        </>
      )}
    </section>
  )
}
